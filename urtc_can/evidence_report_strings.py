def text(language: str, key: str, **values: object) -> str:
    """The text in the language (English when the language or the key is missing), with the ``{placeholders}`` filled."""
    table = STRINGS.get(language) or STRINGS["english"]
    template = table.get(key) or STRINGS["english"].get(key) or key
    return re.sub(r"\{(\w+)\}", lambda m: str(values.get(m.group(1), m.group(0))), template)
