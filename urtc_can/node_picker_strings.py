def fail_key(reason: str) -> str:
    """The key of the text for a ``multinode_host.NodeNotReady`` reason (matched on the words it contains)."""
    text_ = reason.lower()
    for word, key in (("announced", "NP_FAIL_NOT_ANNOUNCED"), ("gone", "NP_FAIL_GONE"), ("address", "NP_FAIL_CONFLICT"), ("fault", "NP_FAIL_FAULT"),
                      ("bootloader", "NP_FAIL_BOOTLOADER"), ("confirm", "NP_FAIL_UNCONFIRMED")):
        if word in text_:
            return key
    return "NP_FAIL_OTHER"


def text(language: str, key: str, **values: object) -> str:
    """The text in the language (English when the language or the key is missing), with the ``{placeholders}`` filled."""
    table = STRINGS.get(language) or STRINGS["english"]
    template = table.get(key) or STRINGS["english"].get(key) or key
    return re.sub(r"\{(\w+)\}", lambda m: str(values.get(m.group(1), m.group(0))), template)
