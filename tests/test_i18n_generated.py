"""The language files of this program are written by tools/i18n_generate.py of URTC-COMMON from its catalog: nobody edits them by hand.

``urtc_i18n.lock.json`` lists every generated file with its SHA-256 (line ends do not count). A file that differs, a file that is missing and
a language file that is not in the lock all fail here, with no need of the other repository; the comparison with what the catalog generates is made
there (``python tools/i18n_generate.py check``). This file is copied by ``i18n_generate.py sync``: change the original, not this copy.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "urtc_i18n.lock.json"
SELF = "tests/test_i18n_generated.py"


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def _lock() -> dict:
    return json.loads(LOCK.read_text(encoding="utf-8"))


def test_the_lock_names_the_catalog_and_the_generated_files():
    lock = _lock()
    assert lock["format"] == 1 and lock["catalog"].startswith("spec/i18n/catalog/") and len(lock["catalog_sha256"]) == 64
    languages = [path for path in lock["files"] if not path.startswith("tests/")]
    assert len(languages) in (1, 8), languages  # a file of the texts of each language, or the one table that holds the eight


def test_a_generated_file_is_not_edited_by_hand():
    for relative, expected in _lock()["files"].items():
        found = ROOT / relative
        assert found.is_file(), f"{relative} is missing: run tools/i18n_generate.py sync of URTC-COMMON"
        assert _digest(found) == expected, f"{relative} differs from the lock: change the catalog of URTC-COMMON and sync, do not edit the file"


def test_there_is_no_language_file_the_catalog_does_not_know():
    files = set(_lock()["files"])
    for pattern in ("language/*.lng", "src/locales/*.json"):
        for found in ROOT.glob(pattern):
            assert found.relative_to(ROOT).as_posix() in files, f"{found.name} is not generated by the catalog"
